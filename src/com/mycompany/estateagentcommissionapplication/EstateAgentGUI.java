    // I process the information entered by the user.
    private void processReport() {

        // I collect the information from the form.
        String location = String.valueOf(cmbAgentLocation.getSelectedItem());
        String name = txtAgentName.getText().trim();
        String price = txtPropertyPrice.getText().trim();
        String percentage = txtCommissionPercentage.getText().trim();

        // I create a Data object using the entered information.
        Data data = new Data(location, name, price, percentage);

        // I check whether the entered information is valid.
        if (!estateAgent.ValidateData(data)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter valid information in all fields.",
                    "Invalid Information",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        try {

            // I calculate the estate agent commission.
            double commission = estateAgent.CalculateCommission(price, percentage);

            // I convert the commission percentage into a number.
            double commissionPercentage = Double.parseDouble(percentage);

            // I convert the property price into a number.
            double propertyPrice = Double.parseDouble(price);

            // I create the estate agent report.
            String report = String.format(
                    Locale.US,
                    "ESTATE AGENT REPORT%n%n"
                    + "AGENT LOCATION: %s%n%n"
                    + "AGENT NAME: %s%n%n"
                    + "COMMISSION PERCENTAGE: %.1f%%%n%n"
                    + "PROPERTY PRICE: R %.1f%n%n"
                    + "CALCULATED COMMISSION: R %.1f",
                    location,
                    name,
                    commissionPercentage,
                    propertyPrice,
                    commission
            );

            // I display the report in the text area.
            txtEstateAgentReport.setText(report);

        } catch (NumberFormatException e) {

            // I display a message if the numbers are invalid.
            JOptionPane.showMessageDialog(
                    this,
                    "Please enter valid numbers for the property price and commission.",
                    "Calculation Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

