    // I save the estate agent report to a text file.
    private void saveReport() {

        // I check whether a report has been generated.
        if (txtEstateAgentReport.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please process the report before saving.",
                    "No Report",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // I save the report in a file called report.txt.
        try (FileWriter writer = new FileWriter("report.txt")) {

            // I write the report into the text file.
            writer.write(txtEstateAgentReport.getText());

            JOptionPane.showMessageDialog(
                    this,
                    "Report saved successfully as report.txt."
            );

        } catch (IOException e) {

            // I display a message if the report cannot be saved.
            JOptionPane.showMessageDialog(
                    this,
                    "The report could not be saved.",
                    "File Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }


